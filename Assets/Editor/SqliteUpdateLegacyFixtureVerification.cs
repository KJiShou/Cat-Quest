using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using UnityEditor;
using UnityEngine;

// Explicit request only. Does not touch GameDataManager, PlayerPrefs, scenes,
// or the live player directory. The driver copies, rather than modifies, this fixture.
[InitializeOnLoad]
public static class SqliteUpdateLegacyFixtureVerification
{
    const string Request = "Temp/create-sqlite-updater-legacy.request";
    const string Result = "Temp/create-sqlite-updater-legacy.result";
    sealed class Clock : ITaskClock
    {
        readonly DateTimeOffset captured = DateTimeOffset.Now;
        public DateTime LocalNow => captured.LocalDateTime;
        public DateTime UtcNow => captured.UtcDateTime;
    }
    [Serializable] sealed class Evidence
    {
        public string utc, unity, fixture, sha256, generator, limitation;
        public int version, tasks, history, experience, fishCoins, tickets;
        public bool passed;
        public List<string> checks = new List<string>();
    }
    static SqliteUpdateLegacyFixtureVerification() { EditorApplication.update += Poll; }
    static void Poll()
    {
        if (EditorApplication.isCompiling || EditorApplication.isUpdating || EditorApplication.isPlayingOrWillChangePlaymode || !File.Exists(Request)) return;
        File.Delete(Request);
        string folder = Path.GetFullPath(Path.Combine("Temp/SQLiteMigrationVerification", "updater-legacy-" + DateTime.UtcNow.ToString("yyyyMMdd-HHmmssfff") + "-" + Guid.NewGuid().ToString("N")));
        Directory.CreateDirectory(folder);
        try {
            var evidence = Generate(folder);
            string report = Path.Combine(folder,"provenance.json");
            File.WriteAllText(report,JsonUtility.ToJson(evidence,true));
            File.WriteAllText(Result,"PASS\n" + evidence.fixture + "\n" + report);
        } catch (Exception error) {
            File.WriteAllText(Path.Combine(folder,"failure.txt"),error.ToString());
            File.WriteAllText(Result,"FAIL\n" + folder + "\n" + error);
            Debug.LogException(error);
        }
    }
    static Evidence Generate(string folder)
    {
        string path = Path.Combine(folder,"legacy-taskservice.json");
        if (File.Exists(path)) throw new InvalidOperationException("Legacy fixture must be new.");
        var clock = new Clock();
        var store = new PlayerDataStore(path);
        var service = new TaskService(store,clock);
        var evidence = new Evidence { utc=DateTime.UtcNow.ToString("O"), unity=Application.unityVersion, fixture=path,
            generator="Actual legacy TaskService with PlayerDataStore and an injected fixed clock",
            limitation="Generated by current retained legacy JSON code; this does not execute an archived old Unity binary." };
        void Check(bool valid,string detail) { if(!valid) throw new InvalidOperationException(detail + ": " + service.LastError); evidence.checks.Add(detail); }
        Check(service.RenamePlayer("迁移验证猫"),"Legacy RenamePlayer writes player identity");
        var settings = service.Settings; settings.notificationsEnabled=false; settings.soundVolume=0; settings.musicVolume=0;
        Check(service.SaveSettings(settings),"Legacy SaveSettings disables notifications and audio");
        Check(service.SaveTag(null,"迁移验证","#3D5FC3",out string tag),"Legacy SaveTag creates a Unicode tag");
        string deleted = null;
        for(int i=0;i<3;i++) {
            Check(service.Upsert(new QuestTask { title="Legacy completed task " + (i+1), difficulty=TaskDifficulty.Hard, tagIds=new List<string>{tag} },null,out string id),"Legacy Upsert creates reward fixture " + (i+1));
            Check(service.Complete(id,true),"Legacy Complete persists original reward receipt " + (i+1));
            if(i==0) deleted=id;
        }
        Check(service.Delete(deleted),"Legacy task deletion retains its historical reward snapshot");
        var pending = new QuestTask { title="更新后继续的任务", description="Unicode migration fixture\nKeep the original snapshot, tags and subtasks.", tagIds=new List<string>{tag},
            subtasks=new List<QuestSubtask>{new QuestSubtask{id="legacy-step-1",title="Review migrated progress"},new QuestSubtask{id="legacy-step-2",title="Continue in SQLite"}} };
        Check(service.Upsert(pending,new[]{"legacy-step-1"},out _),"Legacy Upsert preserves partial subtask progress on an active task");
        Check(service.SaveTutorial(new TutorialProgress { version=1,dismissed=true,taskStep=4,announcedLevel=service.RewardLevel,read=new List<string>{"tasks","focus"} }),"Legacy tutorial state disables onboarding for native handoff verification");
        var reloaded = new PlayerDataStore(path).Data;
        Check(JsonUtility.ToJson(reloaded)==JsonUtility.ToJson(store.Data),"Legacy disk reload preserves every generated field");
        Check(reloaded.username=="迁移验证猫" && !reloaded.settings.notificationsEnabled && reloaded.tasks.Count>0,"Fixture has explicit identity, tasks and safe notification settings");
        Check(service.CanAccess(ProgressionFeature.Focus) && reloaded.focusSessions.Count==0 && reloaded.rewardDays.All(day=>day.focusMinutes==0),"Focus is unlocked with all reward allowance remaining");
        Check(reloaded.battles.All(b=>b.outcome!=BattleOutcome.Running),"Fixture has no active battle");
        using(var hash=SHA256.Create()) evidence.sha256=BitConverter.ToString(hash.ComputeHash(File.ReadAllBytes(path))).Replace("-","").ToLowerInvariant();
        evidence.version=reloaded.version;evidence.tasks=reloaded.tasks.Count;evidence.history=reloaded.history.Count;
        evidence.experience=reloaded.experience;evidence.fishCoins=reloaded.fishCoins;evidence.tickets=reloaded.tickets;evidence.passed=true;
        return evidence;
    }
}
